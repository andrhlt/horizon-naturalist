"""Generate the review prototype's fixed Rust tables from entity-metadata.json."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
metadata = json.loads((root / 'entity-metadata.json').read_text())
project = root.parent / 'src/current'

def rust(s):
    return json.dumps(s)

rows = []
for name, entry in sorted(metadata.items()):
    if not entry['attributes']:
        continue
    attrs = ', '.join(f'({rust("minecraft:" + key)}, {float(value)!r})'
                      for key, value in sorted(entry['attributes'].items()) if value is not None)
    # These five selected templates carry attack_damage where Java's fixture
    # says the attribute is absent; the registrar cannot remove it.
    template = entry['template']
    if name in {'naturalist:bird', 'naturalist:butterfly', 'naturalist:dragonfly', 'naturalist:firefly', 'naturalist:hedgehog'}:
        template = 'minecraft:wandering_trader'
    rows.append(f'    ({rust(name)}, {rust(template)}, &[{attrs}]),')
(project / 'profiles.rs').write_text('''// Generated by migration/generate_metadata.py; source: entity-metadata.json.
pub const PROFILES: &[(&str, &str, &[(&str, f64)])] = &[
''' + '\n'.join(rows) + '\n];\n')

rows = []
for name, entry in sorted(metadata.items()):
    w, h, eye = entry['dimensions']
    rows.append(f'        ({rust(name)}, {rust(entry["template"])}, {rust(entry["category"])}, {w!r}, {h!r}, {eye!r}),')
(project / 'metadata.rs').write_text('''// Generated by migration/generate_metadata.py; source: entity-metadata.json.
fn metadata(
    types: &mut HashMap<String, horizon_client::mobs::MobType>,
    catalog: &horizon_world::attributes::entity::Catalog,
) {
    for (name, template, category, width, height, eyes) in [
''' + '\n'.join(rows) + '''
    ] {
        if !types.contains_key(name) { continue; }
        let Some(base) = types.get(template) else { continue; };
        // Preserve content sound selections when replacing the mod type with its template.
        let sound_overrides = types.get(name).map(|registered| registered.sound_overrides.clone());
        let mut kind = base.clone();
        if let Some(sound_overrides) = sound_overrides {
            kind.sound_overrides = sound_overrides;
        }
        kind.id = name.to_owned();
        kind.category = category.to_owned();
        kind.width = width;
        kind.height = height;
        kind.eye_height = eyes;
        if let Some(row) = catalog.entity_row(name) {
            kind.take_attribute_row(Arc::new(row), catalog);
        }
        if name == "naturalist:deer" {
            let apples: Arc<[String]> = Arc::from(["minecraft:apple".to_owned()]);
            kind.food = apples.clone();
            kind.tempt = apples;
        }
        if name == "naturalist:caterpillar" { kind.baby_scale = 1.0; }
        match name {
            "naturalist:giraffe" => kind.max_head_y_rot = 45.0,
            "naturalist:elephant" | "naturalist:mammoth" => kind.max_head_y_rot = 35.0,
            _ => (),
        }
        types.insert(name.to_owned(), kind);
    }
}
''')
